<script setup lang="ts">
import { computed, onBeforeUnmount, onMounted, ref } from 'vue'
import AiGeneratedImageCard from '@/components/AiGeneratedImageCard.vue'
import StylePromptInput from '@/components/StylePromptInput.vue'
import { useAiGeneratedImages } from '@/composables/useAiGeneratedImages'
import type { AiGeneratedImageJob } from '@/types/aiImageGeneration'
import type { TrackVideoJobStatus } from '@/types/trackVideo'
import { formatRelativeDate } from '@/utils/formatters'

const {
  jobs,
  activeJobCount,
  jobsLoading,
  refreshing,
  submitting,
  deletingJobIds,
  error,
  lastUpdatedAt,
  loadJobs,
  refreshJobs,
  submitJob,
  deleteJob,
  clearError,
  stopPolling,
} = useAiGeneratedImages()

const prompt = ref('')
const trackUrl = ref<string | null>('')
const promptTouched = ref(false)
const trackUrlTouched = ref(false)
const showSuccess = ref(false)
const showDeleteSuccess = ref(false)
const deleteDialogOpen = ref(false)
const deleteCandidate = ref<AiGeneratedImageJob | null>(null)
const search = ref('')
const statusFilter = ref<'all' | TrackVideoJobStatus>('all')

const promptIdeas = [
  {
    label: 'Woodblock print',
    prompt: 'Album cover art for {trackGenre} track titled "{trackName}". '
      + 'Woodblock linocut style, earthy green and rust tones, tactile texture, '
      + 'moody minimalism, includes text "{trackName}".',
  },
  {
    label: 'Dreamlike editorial',
    prompt: 'Dreamlike editorial artwork for the {trackGenre} track "{trackName}". '
      + 'Translucent fabrics, soft fog, a pearl and cobalt palette, cinematic studio light, '
      + 'and a surreal composition inspired by the track title.',
  },
]

const statusOptions = [
  { title: 'All statuses', value: 'all' },
  { title: 'Queued', value: 'queued' },
  { title: 'Generating', value: 'processing' },
  { title: 'Ready', value: 'completed' },
  { title: 'Failed', value: 'failed' },
]

function validateTrackUrl(value: string): string | null {
  if (!value) {
    return null
  }

  try {
    const url = new URL(value)
    const allowedHosts = ['bandlab.com', 'www.bandlab.com', 'test.bandlab.com']
    const uuid = '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
    const trackPath = new RegExp(`^/track/${uuid}/?$`, 'i')
    const queryEntries = [...url.searchParams.entries()]
    const hasValidQuery = queryEntries.length === 0
      || (
        queryEntries.length === 1
        && queryEntries[0][0] === 'revId'
        && new RegExp(`^${uuid}$`, 'i').test(queryEntries[0][1])
      )

    if (
      url.protocol !== 'https:'
      || !allowedHosts.includes(url.hostname)
      || !trackPath.test(url.pathname)
      || !hasValidQuery
      || url.hash
    ) {
      return 'Use a valid public BandLab track URL.'
    }

    return null
  } catch {
    return 'Use a valid public BandLab track URL.'
  }
}

const rawPromptError = computed(() => {
  const value = prompt.value.trim()
  if (!value) {
    return 'A prompt is required.'
  }
  if (prompt.value.length > 2000) {
    return 'Keep the prompt within 2,000 characters.'
  }
  if (
    (value.includes('{trackName}') || value.includes('{trackGenre}'))
    && !trackUrl.value?.trim()
  ) {
    return 'Add a BandLab track URL above to use track placeholders.'
  }
  return null
})
const rawTrackUrlError = computed(() => validateTrackUrl(trackUrl.value?.trim() || ''))
const promptError = computed(() => promptTouched.value ? rawPromptError.value : null)
const trackUrlError = computed(() => trackUrlTouched.value ? rawTrackUrlError.value : null)
const deletingCandidate = computed(() => (
  deleteCandidate.value
    ? deletingJobIds.value.has(deleteCandidate.value.jobId)
    : false
))
const completedJobs = computed(() => jobs.value.filter(job => job.status === 'completed'))
const hasFilters = computed(() => (
  search.value.trim().length > 0 || statusFilter.value !== 'all'
))
const filteredJobs = computed(() => {
  const query = search.value.trim().toLowerCase()
  return jobs.value.filter(job => {
    if (statusFilter.value !== 'all' && job.status !== statusFilter.value) {
      return false
    }
    if (!query) {
      return true
    }

    return [
      job.promptTemplate,
      job.resolvedPrompt,
      job.track?.name,
      job.track?.genre,
      job.jobId,
    ].some(value => value?.toLowerCase().includes(query))
  })
})

function usePromptIdea(value: string): void {
  prompt.value = value
  promptTouched.value = false
}

async function handleSubmit(): Promise<void> {
  promptTouched.value = true
  trackUrlTouched.value = true
  if (rawPromptError.value || rawTrackUrlError.value) {
    return
  }

  clearError()
  const created = await submitJob(prompt.value, trackUrl.value?.trim() || undefined)
  if (created) {
    showSuccess.value = true
    prompt.value = ''
    trackUrl.value = ''
    promptTouched.value = false
    trackUrlTouched.value = false
  }
}

function clearFilters(): void {
  search.value = ''
  statusFilter.value = 'all'
}

function requestDelete(job: AiGeneratedImageJob): void {
  clearError()
  deleteCandidate.value = job
  deleteDialogOpen.value = true
}

function closeDeleteDialog(): void {
  if (deletingCandidate.value) {
    return
  }

  deleteDialogOpen.value = false
  deleteCandidate.value = null
}

async function confirmDelete(): Promise<void> {
  if (!deleteCandidate.value) {
    return
  }

  const deleted = await deleteJob(deleteCandidate.value.jobId)
  if (deleted) {
    deleteDialogOpen.value = false
    deleteCandidate.value = null
    showDeleteSuccess.value = true
  }
}

onMounted(() => {
  void loadJobs()
})

onBeforeUnmount(stopPolling)
</script>

